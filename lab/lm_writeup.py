"""A readable account of what a constructor run found on an LM target:  python3 lab/lm_writeup.py <target> <run id>

Writes FINDINGS.md in the run folder from what is on disk (nothing is recomputed): the reader's own description of
the mechanism, where each variable lives (depth x position), every verified and failing test next to its controls,
the prior-only controls of the same target, the transfer tests and the circuit. Called by lab/lm_post.py.
"""
import json, sys
from pathlib import Path

LAB = Path(__file__).resolve().parent
sys.path.insert(0, str(LAB))
import judge as J  # noqa: E402


def pct(x):
    return "-" if x is None else f"{x:.1%}"


def writeup(tid, rid):
    rdir = LAB / "constructions" / tid / rid
    rec = json.loads((rdir / "run.json").read_text())
    meta = json.loads((LAB / "models" / tid / "meta.json").read_text())
    if (rdir / "report.json").exists():
        rep, src = json.loads((rdir / "report.json").read_text()), (rdir / "construction.py").read_text()
    else:
        n = rec.get("best")
        if not n:
            return None
        rep, src = json.loads((rdir / f"submission_{n:02d}.json").read_text()), (rdir / f"submission_{n:02d}.py").read_text()
    try:
        ns = {"np": __import__("numpy"), "math": __import__("math")}
        exec(compile(src, "construction", "exec"), ns)
        desc = ns.get("DESCRIPTION", "")
    except Exception:  # noqa: BLE001
        desc = ""
    v, b = rep["verdict"], rep["behaviour"]
    c = rec["config"]
    L = [f"# {meta.get('name', tid)}: what the constructor found", "",
         f"*Run `{rid}` ({c.get('title', '')}), model `{meta['model']}`, {len(rec['steps'])} steps, ${rec.get('cost', 0):.2f}. "
         f"Generated by `lab/lm_writeup.py` from the run folder.*", "",
         "## Verdict", "",
         f"**{'VERIFIED AND COMPLETE' if v.get('complete') else ('VERIFIED (partial)' if v.get('verified') else 'NOT VERIFIED')}**: "
         f"{v.get('stages_verified', 0)} of {v.get('stages_total', '?')} stages verified. Behaviour: the construction makes the network's decision on "
         f"{pct(b['match'])} of held-out prompts (a constant answer: {pct(b.get('baseline_constant_match'))}).", "",
         "## The task", "", meta["answer"]["short"], "", meta["domain"]["text"], "",
         "## The mechanism, in the reader's words", "", desc.strip() or "(no description)", ""]
    # where things live
    cells, poss, depths = {}, [], []
    for var, info in rep["variables"].items():
        for s in info["sites"]:
            if s.startswith("resid"):
                d, p = s[5:].split("@")
                cells.setdefault((int(d), p), []).append(var)
                if p not in poss:
                    poss.append(p)
                if int(d) not in depths:
                    depths.append(int(d))
    if cells:
        order = sorted(poss, key=lambda p: meta["roles"].get(p, 99) if isinstance(meta["roles"].get(p), int) else 99)
        L += ["## Where each variable lives", "", "Rows: depth (the residual stream entering that block). Columns: token positions. "
              "A cell lists the variables the construction places there; ✓ = the cut at that depth passed every test.", "",
              "| depth | " + " | ".join(order) + " | cut |", "|---|" + "---|" * (len(order) + 1)]
        for d in sorted(depths):
            r = rep["sites"].get(f"cut{d}", {})
            L.append(f"| resid{d} | " + " | ".join(", ".join(cells.get((d, p), [])) for p in order) + f" | {'✓' if r.get('pass') else '✗'} |")
        L.append("")
    L += ["## Tests, unit by unit (held-out prompts)", "", "| unit | substitute | mean-ablate | remove named (random) | named dims / PCs needed | verdict |",
          "|---|---|---|---|---|---|"]
    for u, r in rep["sites"].items():
        L.append(f"| {u} | {pct(r['substitute_match'])} | {pct(r['mean_ablate_match'])} | {pct(r['remove_named_match'])} ({pct(r.get('remove_random_match'))}) | "
                 f"{r.get('used_rank', r['named_rank'])} / {r['pca_sufficient_rank']} | {'pass' if r.get('pass') else 'fail'} |")
    L += ["", "| intervention | unit | right when the network changed | network changed | controls: no change / random subspace / attribution patching |",
          "|---|---|---|---|---|"]
    for t in rep["interventions"]:
        L.append(f"| {t['mode']} {t['variable']} | {t['site']} | {pct(t['agreement_when_changed'])} | {pct(t['network_changed'])} | "
                 f"{pct(t['baseline_no_change'])} / {pct(t.get('control_random_subspace'))} / {pct(t.get('attribution_patching_when_changed'))} |")
    if v.get("fails"):
        L += ["", "Failing: " + "; ".join(v["fails"])]
    # controls of the same target
    ctrl = []
    for f in sorted((LAB / "constructions" / tid).glob("*/run.json")):
        r2 = json.loads(f.read_text())
        cc = r2["config"]
        if f.parent.name == rid or not (cc.get("told") or not cc.get("weights", True) or cc.get("variant") != "original"):
            continue
        rj = f.parent / "rejudge_clear_decisions.json"
        sub = json.loads(rj.read_text()) if rj.exists() else (r2.get("verdict") or {})
        vv = sub.get("verdict", sub)
        kind = "prior-only (no access to the model, told the behaviour)" if not cc.get("weights", True) else f"{cc.get('variant')} {'told' if cc.get('told') else 'blinded'}"
        ctrl.append(f"| {f.parent.name} | {kind} | {vv.get('stages_verified', 0)} of {vv.get('stages_total', '?')} |")
    if ctrl:
        L += ["", "## Controls on the same target", "", "| run | control | stages verified |", "|---|---|---|"] + ctrl
    for f in sorted(rdir.glob("transfer_*.txt")):
        L += ["", f"## Transfer: {f.stem[9:]}", "", "```", f.read_text().strip(), "```"]
    if (rdir / "circuit.txt").exists():
        L += ["", "## Circuit: which components write each verified variable", "", "```", (rdir / "circuit.txt").read_text().strip(), "```"]
    L += ["", "## Reproduce", "", f"```\npython3 lab/judge.py {tid} lab/constructions/{tid}/{rid}/construction.py\npython3 lab/lm_post.py {tid} {rid}\n```", ""]
    (rdir / "FINDINGS.md").write_text("\n".join(L))
    return rdir / "FINDINGS.md"


if __name__ == "__main__":
    print(writeup(sys.argv[1], sys.argv[2]))
