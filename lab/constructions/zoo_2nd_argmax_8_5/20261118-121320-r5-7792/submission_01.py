def model(x, iv):
    s = np.zeros((len(x), 8))
    for t in range(5):
        s = iv('h%d'%(t+1), np.maximum(x[:,t:t+1]*W_x + s@W_h, 0))
    sc4 = s @ Wc4
    sc5 = -sc4.sum(1, keepdims=True)
    return np.concatenate([sc4, sc5], 1)
