def model(x, iv):
    B = x.shape[0]
    h = np.zeros((B, 8))
    for t in range(8):
        h = np.maximum(h @ WH + x[:, t:t + 1] * WX[None, :], 0.0)
        h = iv("h%d" % (t + 1), h)
    d = h @ W7
    return np.concatenate([np.zeros((B, 1)), d], axis=1)

