def model(x,iv):
    B=len(x)
    tk=[iv('tok%d'%p,(x[:,p][:,None]==np.arange(6))*1.) for p in range(6)]
    E=np.stack([tk[p]@WE+WP[p] for p in range(6)],1)
    S=np.einsum('bpd,bjd->bpj',E@A0,E)
    a=np.exp(S-S.max(2,keepdims=True));a/=a.sum(2,keepdims=True)
    a=iv('pat0',a.reshape(B,-1)).reshape(B,6,6)
    r=E+np.einsum('bpj,bjd->bpd',a,E@P0)
    q=r[:,5]@A1
    T=np.einsum('bd,bjd->bj',q,r)
    a1=np.exp(T-T.max(1,keepdims=True));a1/=a1.sum(1,keepdims=True)
    a1=iv('a1_last',a1)
    return iv('score',r[:,5]@WU+np.einsum('bj,bjd->bd',a1,r@M))

