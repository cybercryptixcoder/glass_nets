def model(x, iv):
    B = x.shape[0]
    tok = [iv('tok%d'%p, (x[:,p][:,None]==np.arange(6)).astype(float)) for p in range(6)]
    E = np.stack([tok[p] @ WE + WP[p] for p in range(6)], 1)          # [B,6,8]
    S0 = np.einsum('bpd,bjd->bpj', E @ A0, E)
    a0 = np.exp(S0 - S0.max(2, keepdims=True)); a0 /= a0.sum(2, keepdims=True)
    a0 = iv('pat0', a0.reshape(B, -1)).reshape(B, 6, 6)
    r0 = E + np.einsum('bpj,bjd->bpd', a0, E @ P0)                    # [B,6,8]
    q = r0[:, 5] @ A1
    S1 = np.einsum('bd,bjd->bj', q, r0)
    a1 = np.exp(S1 - S1.max(1, keepdims=True)); a1 /= a1.sum(1, keepdims=True)
    a1 = iv('a1_last', a1)
    sc = r0[:, 5] @ WU + np.einsum('bj,bjd->bd', a1, r0 @ M)
    return iv('score', sc)

