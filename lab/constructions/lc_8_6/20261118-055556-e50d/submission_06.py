    B = x.shape[0]
    h = np.stack([iv("emb%d" % p, E[x[:, p]] + P[p]) for p in range(6)], 1)
    lg = np.exp((np.einsum('bqd,de,bke->bqk', h, A0, h) / S) - 0)
    lg = lg / lg.sum(-1, keepdims=True)
    a0 = iv("a0", lg.reshape(B, 36)).reshape(B, 6, 6)
    r0 = iv("r0", (h + np.einsum('bpk,bkd->bpd', a0, h @ VO0)).reshape(B, 48)).reshape(B, 6, 8)
    l1 = np.einsum('bd,de,bke->bk', r0[:, 5], A1, r0) / S
    l1 = np.exp(l1 - l1.max(-1, keepdims=True))
    a1 = iv("a1", l1 / l1.sum(-1, keepdims=True))
    r1 = iv("r1", r0[:, 5] + np.einsum('bk,bkd->bd', a1, r0 @ VO1))
    return r1 @ U

