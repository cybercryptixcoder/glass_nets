def _sm(S_):
    S_ = S_ - S_.max(-1, keepdims=True)
    P = np.exp(S_)
    return P/P.sum(-1, keepdims=True)

def model(x, iv):
    x = np.asarray(x)
    B = x.shape[0]
    rows = np.arange(B)
    toks = []
    for p in range(5):
        oh = np.zeros((B, 5))
        oh[rows, x[:, p].astype(int)] = 1.0
        toks.append(iv("tok%d" % p, oh))
    E = np.stack([toks[p]@WE + WP[p] for p in range(5)], 1)     # [B,5,6]
    P0 = _sm(np.einsum('bpi,ij,bqj->bpq', E, A0, E)/np.sqrt(6))
    add0 = P0@(E@B0)
    R0 = np.stack([iv("r0p%d" % p, E[:, p, :] + add0[:, p, :]) for p in range(5)], 1)
    P1 = _sm(np.einsum('bpi,ij,bqj->bpq', R0, A1, R0)/np.sqrt(6))
    add1 = P1@(R0@B1)
    last = iv("r1p4", R0[:, 4, :] + add1[:, 4, :])
    return last@WU

