def _attn(e, A, Bm):
    s = (e @ A) @ e.transpose(0, 2, 1) * SQ
    s = s - s.max(2, keepdims=True)
    P = np.exp(s)
    P = P / P.sum(2, keepdims=True)
    return P @ (e @ Bm)

def model(x, iv):
    B = x.shape[0]
    toks = []
    for p in range(5):
        oh = np.zeros((B, 5))
        oh[np.arange(B), x[:, p].astype(int)] = 1.0
        toks.append(iv("tok%d" % p, oh))
    T = np.stack(toks, 1)
    e = T @ W_E + W_pos[None]
    r0 = e + _attn(e, A0, B0)
    r0 = np.stack([iv("r0p%d" % p, r0[:, p, :]) for p in range(5)], 1)
    r1 = r0 + _attn(r0, A1, B1)
    r1 = np.stack([iv("r1p%d" % p, r1[:, p, :]) for p in range(5)], 1)
    return r1[:, 4, :] @ W_U

