def smatch(s):
    s = s - s.max(2, keepdims=True)
    e = np.exp(s)
    return e / e.sum(2, keepdims=True)

def model(x, iv):
    t = x.astype(int)
    B = t.shape[0]
    oh = [iv("tok%d" % p, np.eye(5)[t[:, p]]) for p in range(5)]
    xp = np.concatenate([np.stack(oh, 1), np.zeros((B, 5, 1))], 2) + P[None]
    pat0 = iv("pat0", smatch(xp @ M0 @ xp.transpose(0, 2, 1) / np.sqrt(6)).reshape(B, 25))
    a0 = iv("a0", (pat0.reshape(B, 5, 5) @ xp @ OV0).reshape(B, 30))
    r0 = iv("r0", (xp + a0.reshape(B, 5, 6)).reshape(B, 30))
    X0 = r0.reshape(B, 5, 6)
    pat1 = iv("pat1", smatch(X0 @ M1 @ X0.transpose(0, 2, 1) / np.sqrt(6)).reshape(B, 25))
    a1 = iv("a1", (pat1.reshape(B, 5, 5) @ X0 @ OV1).reshape(B, 30))
    r1 = iv("r1", (X0 + a1.reshape(B, 5, 6)).reshape(B, 30))
    return r1.reshape(B, 5, 6)[:, 4, :] @ U

