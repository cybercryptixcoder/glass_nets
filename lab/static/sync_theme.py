"""Copy the shared theme into each page.

The lab server only serves the three pages (index, constructor, catalog), so shared files can't be linked without a
server change. These files stay the single sources of truth, and this script keeps the inlined copies equal:

    theme.css  -> between  /* @theme:begin ... */  and  /* @theme:end */        (inside the page's <style>)
    shell.html -> between  <!-- @shell:begin ... -->  and  <!-- @shell:end -->  (the sidebar, inside <body>)
    shell.js   -> between  /* @shell-js:begin ... */  and  /* @shell-js:end */  (top of the page's <script>)

    python3 lab/static/sync_theme.py          # write
    python3 lab/static/sync_theme.py --check  # exit 1 if any page is out of date (for tests)
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAGES = ["index.html", "constructor.html", "catalog.html"]
NOTE = "(generated by sync_theme.py; do not edit here)"
BLOCKS = [  # (source file, begin marker, end marker, where to put it the first time)
    ("theme.css", f"/* @theme:begin {NOTE} */", "/* @theme:end */", "<style>"),
    ("shell.html", f"<!-- @shell:begin {NOTE} -->", "<!-- @shell:end -->", None),
    ("shell.js", f"/* @shell-js:begin {NOTE} */", "/* @shell-js:end */", "<script>"),
]


def sync(html: str) -> str:
    for src, begin, end, first in BLOCKS:
        body = (HERE / src).read_text().strip()
        block = f"{begin}\n{body}\n{end}"
        stem = begin.split(" (")[0]
        pat = re.compile(re.escape(stem) + r".*?" + re.escape(end), re.S)
        if pat.search(html):
            html = pat.sub(lambda _: block, html, count=1)
        elif first:
            html = html.replace(first, first + "\n" + block + "\n", 1)
        # the shell (sidebar) has no default place: a page opts in by carrying the two markers
    return html


def main(check: bool) -> int:
    stale = []
    for name in PAGES:
        path = HERE / name
        html = path.read_text()
        new = sync(html)
        if new != html:
            stale.append(name)
            if not check:
                path.write_text(new)
    if check:
        print("out of date: " + ", ".join(stale) if stale else "all pages carry the current theme")
        return 1 if stale else 0
    print("updated: " + (", ".join(stale) or "nothing (already current)"))
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
