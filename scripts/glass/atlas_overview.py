"""One table over every saved atlas (results/glass/atlas/<t>_d4.json), for the write-up: size, mechanisms, explanations,
the certificate (v3) against the task rule, functional groups against the shuffled control. Writes
results/glass/atlas/OVERVIEW.md and prints it."""
import json, sys
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parents[2]; sys.path.insert(0, str(ROOT / "lab"))
import atlas
A = ROOT / "results/glass/atlas"
DEV = {"zoo_argmedian_8_5", "zoo_argmedian_8_7", "zoo_argmedian_16_5", "zoo_argmedian_16_7", "zoo_2nd_argmax_16_10", "zoo_2nd_argmax_16_10_s0",
       "zoo_2nd_argmax_8_8", "zoo_2nd_argmax_8_5"}
A18 = {"zoo_2nd_argmax_16_5_s0", "zoo_2nd_argmax_16_8_s0", "zoo_2nd_argmax_32_5_s0", "zoo_argmedian_32_5_s0", "zoo_2nd_argmax_32_10_s0", "zoo_argmedian_32_7_s0"}


def params(t):
    m = ROOT / "lab/models" / t / "weights.npz"
    return int(sum(v.size for v in np.load(m).values())) if m.exists() else None


rows = []
for f in sorted(A.glob("*_d4.json")):
    if "_shuffled_" in f.name:
        continue
    t = f.name[:-len("_d4.json")]; a = json.loads(f.read_text())
    mech = [x for m in a["matrices"].values() for x in m["mechanisms"]]
    sw = [x for x in mech if x["trigger"]["rule"] not in ("always", "never")]
    trusted = sum(atlas._conf(x) >= atlas.TRUSTED for x in sw)
    task = sum(x["trigger"].get("task_level", {}).get("confidence_clear", 0) >= atlas.TRUSTED for x in sw)
    fid = atlas._fid(a); tr = a["task_rule"]; alone = a["fidelity"].get("mechanisms_alone")
    F = a.get("findings") or atlas.findings(a)
    g = sum(len(v) for v in F["groups"].values())
    cf = A / f"{t}_shuffled_d4.json"
    gc = sum(len(v) for v in atlas.findings(json.loads(cf.read_text()))["groups"].values()) if cf.exists() else None
    role = "planted" if t.startswith("planted") else "dev" if t in DEV else "held out (A18)" if t in A18 else "other"
    p = params(t)
    rows.append((role, t, p, len(mech), len(sw), trusted, task, fid, tr, alone, g, gc))

L = ["# Mechanism atlases: overview", "",
     "Generated by `scripts/glass/atlas_overview.py` from the saved atlases. 'Switched' = mechanisms not always on. "
     "'Trusted' = trigger confidence ≥ 0.9 on clear-cut cases; 'task-level' = of those switched, how many have a trusted trigger in task variables only. "
     "'Rebuilt' = the certificate's fidelity (v3 gate) against the task rule; 'alone' = all mechanisms on, residual removed. "
     "'Groups' = mechanisms whose removal mostly moves the answer between two specific ranks (vs the shuffled-weights control).", "",
     "| set | network | params | mechanisms | switched | trusted | task-level | rebuilt vs task rule | alone | groups (control) |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for role, t, p, n, s, tru, task, fid, tr, alone, g, gc in sorted(rows, key=lambda r: (r[0], r[2] or 0)):
    vs = f"{100 * fid:.1f}% vs {100 * tr:.1f}% {'✓' if fid >= tr else '✗'}" if tr is not None else f"{100 * fid:.1f}%"
    L.append(f"| {role} | {t} | {p or '-'} | {n} | {s} | {tru} | {task} | {vs} | {'-' if alone is None else f'{100 * alone:.1f}%'} | {g}{'' if gc is None else f' ({gc})'} |")
out = "\n".join(L) + "\n"
(A / "OVERVIEW.md").write_text(out); print(out)
